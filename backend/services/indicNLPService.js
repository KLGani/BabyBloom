/**
 * Main NLP Processor:
 * Analyzes question, detects target language, classifies clinical intent,
 * and generates high-fidelity ChatGPT-level response.
 */
function processMultilingualQuestion(userMessage, context = {}, requestedLanguage = "English") {
  // 1. Detect language from text or user preference
  const detectedLanguage = detectScriptLanguage(userMessage, requestedLanguage);

  // 2. Identify clinical/maternal intent
  const intent = detectIntent(userMessage);

  // 3. Select language pack
  const langPack = RESPONSES_BY_LANGUAGE[detectedLanguage] || RESPONSES_BY_LANGUAGE.English;

  // 4. Retrieve synthesized response or generate dynamic open-ended answer
  let reply = langPack[intent];
  if (!reply || intent === "DYNAMIC_SYNTHESIS") {
    reply = generateContextualDynamicResponse(userMessage, context, detectedLanguage);
  }

  return {
    reply,
    detectedLanguage,
    intent,
  };
}

