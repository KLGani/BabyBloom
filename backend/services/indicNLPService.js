// 1. Language Script Detection
function detectScriptLanguage(text, fallbackLanguage = "English") {
  if (!text || typeof text !== "string") return fallbackLanguage;

  const clean = text.trim();

  // Kannada Unicode range: 0C80–0CFF
  if (/[\u0C80-\u0CFF]/.test(clean)) return "Kannada";

  // Devanagari (Hindi) Unicode range: 0900–097F
  if (/[\u0900-\u097F]/.test(clean)) return "Hindi";

  // Tamil Unicode range: 0B80–0BFF
  if (/[\u0B80-\u0BFF]/.test(clean)) return "Tamil";

  // Telugu Unicode range: 0C00–0C7F
  if (/[\u0C00-\u0C7F]/.test(clean)) return "Telugu";

  // Normalize fallback language
  const fb = fallbackLanguage.toLowerCase();
  if (fb.includes("kan")) return "Kannada";
  if (fb.includes("hin")) return "Hindi";
  if (fb.includes("tam")) return "Tamil";
  if (fb.includes("tel")) return "Telugu";

  return "English";
}

